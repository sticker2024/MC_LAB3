# ---------------------------------------------------------------- Step 2
def hex_cells(rings, R=1.0):
    """Axial coords (q, r) of all cells within `rings` rings of the origin,
    plus their (x, y) centres for a pointy-top hexagonal grid of radius R."""
    cells = []
    for q in range(-rings, rings + 1):
        for r in range(-rings, rings + 1):
            if max(abs(q), abs(r), abs(q + r)) <= rings:
                x = R * math.sqrt(3) * (q + r / 2.0)
                y = R * 1.5 * r
                cells.append((q, r, x, y))
    return cells


# ---------------------------------------------------------------- Step 3
def ij_for_N(N):
    """Find integers i >= j >= 0 with N = i^2 + i*j + j^2."""
    for i in range(0, 20):
        for j in range(0, i + 1):
            if i * i + i * j + j * j == N:
                return i, j
    raise ValueError(f"N={N} is not a valid hexagonal cluster size")


def assign_groups(cells, N):
    """Label each cell 1..N.

    The cluster lattice is generated by the offset vectors
        v1 = (i, j)   and   v2 = (-j, i + j)     (axial coordinates),
    whose determinant is i^2 + i*j + j^2 = N. Two cells use the same frequency
    group iff their difference is an integer combination of v1 and v2, i.e. iff
    adj(M) * diff == 0 (mod N). That residue pair identifies the group.
    """
    i, j = ij_for_N(N)
    keys = {}
    for q, r, _, _ in cells:
        keys[(q, r)] = (((i + j) * q + j * r) % N, ((-j) * q + i * r) % N)
    # make labels stable: origin cell is group 1, others numbered by key order
    origin_key = keys[(0, 0)]
    uniq = sorted(set(keys.values()))
    uniq.remove(origin_key)
    label_of = {origin_key: 1}
    for n, k in enumerate(uniq, start=2):
        label_of[k] = n
    assert len(label_of) == N, f"expected {N} groups, found {len(label_of)}"
    return {rc: label_of[k] for rc, k in keys.items()}, (i, j)


def rings_needed(N):
    # enough rings for at least two rings of clusters around the centre one
    return int(math.ceil(2 * math.sqrt(N))) + 1


def measured_reuse_distance(cells, groups, R):
    """Smallest centre-to-centre distance between two distinct cells that share
    a group, divided by R. Should equal sqrt(3N)."""
    best = float("inf")
    for a in range(len(cells)):
        for b in range(a + 1, len(cells)):
            if groups[(cells[a][0], cells[a][1])] == groups[(cells[b][0], cells[b][1])]:
                d = math.hypot(cells[a][2] - cells[b][2], cells[a][3] - cells[b][3])
                best = min(best, d)
    return best / R


# ---------------------------------------------------------------- Step 4-6
def draw_layout(ax, N, R=1.0):
    cells = hex_cells(rings_needed(N), R)
    groups, (i, j) = assign_groups(cells, N)
    cmap = plt.get_cmap("tab20" if N > 10 else "tab10")
    for q, r, x, y in cells:
        g = groups[(q, r)]
        ax.add_patch(RegularPolygon((x, y), numVertices=6, radius=R,
                                    facecolor=cmap((g - 1) % cmap.N), edgecolor="k",
                                    linewidth=0.5, alpha=0.85))
        ax.text(x, y, str(g), ha="center", va="center", fontsize=7)
    ext = (rings_needed(N) + 1) * R * 1.8
    ax.set_xlim(-ext, ext)
    ax.set_ylim(-ext, ext)
    ax.set_aspect("equal")
    ax.axis("off")
    Q = math.sqrt(3 * N)
    ax.set_title(f"N = {N}  (i={i}, j={j}),  Q = {Q:.2f}", fontsize=11)
    return cells, groups


def reuse_layouts(Ns, fname, ncols=2):
    nrows = math.ceil(len(Ns) / ncols)
    fig, axes = plt.subplots(nrows, ncols, figsize=(6 * ncols, 6 * nrows))
    axes = np.atleast_1d(axes).ravel()
    rows = []
    for ax, N in zip(axes, Ns):
        cells, groups = draw_layout(ax, N, R)
        measured = measured_reuse_distance(cells, groups, R)
        rows.append((N, math.sqrt(3 * N), measured, len(set(groups.values())), len(cells)))
    for ax in axes[len(Ns):]:
        ax.axis("off")
    fig.suptitle("Hexagonal frequency-reuse layouts (colour = frequency group)", fontsize=14)
    fig.tight_layout()
    fig.savefig(os.path.join(OUT, fname), dpi=150)
    plt.close(fig)
    return rows


