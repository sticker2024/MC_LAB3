# ----------------------------------------- Lab Task 3: margin x TTT sweep
def sweep(n_seeds=40, rsrp_floor=-100.0):
    margins = np.arange(0, 9, 1.0)
    ttts = np.arange(1, 16)
    cnt = np.zeros((len(margins), len(ttts)))
    low = np.zeros_like(cnt)
    for s in range(n_seeds):
        a, b = make_series(seed=1000 + s)
        for mi, m in enumerate(margins):
            for ti, tt_ in enumerate(ttts):
                ev, _, sr = run_trigger(a, b, m, int(tt_))
                cnt[mi, ti] += len(ev)
                low[mi, ti] += np.sum(sr < rsrp_floor)
    return margins, ttts, cnt / n_seeds, low / n_seeds


